import { posix } from "node:path";

import { publishLlmsText, rebaseMarkdownTargets, rewriteMarkdownTargets } from "@codenhub/tools/documentation";

import { localizePath, type Locale } from "../i18n";

export interface DocumentMarkdownSource {
  /**
   * Authored Markdown body without its frontmatter. Astro's `rawContent()`
   * blanks the frontmatter out with whitespace, which is dropped here.
   */
  body: string;
  /**
   * The language of the page it is published beside. Links to the package's
   * pages point into it, as the page's own links do; links to files keep their
   * one English URL.
   */
  pageLocale?: Locale;
  /** Path relative to the package's `docs/`, such as `guides/setup.md`. */
  relativePath: string;
  siteUrl: string;
  slug: string;
  /**
   * Set when the page shows an English body under a locale: the notice the
   * page shows above it, and the English page's URL. The Markdown opens with
   * both, since it has no page around it to carry the notice.
   */
  untranslated?: { englishUrl: string; notice: string };
}

const LEADING_BLANK_LINES = /^(?:[ \t]*\r?\n)+/;
// The notice opening a generated reference page addresses maintainers, not the
// readers and assistants this copy is published for.
const GENERATED_NOTICE = /^<!-- Generated by `pnpm generate` [^\n]*-->(?:[ \t]*\r?\n)+/;

/**
 * Prepares one page's Markdown for publication beside the page as `index.md`.
 *
 * Package-relative targets the site publishes become absolute site URLs, the
 * rule `llms-full.txt` follows on this site, because the text is meant to be
 * copied, downloaded, and pasted where no base URL exists.
 */
export function publishDocumentMarkdown(source: DocumentMarkdownSource): string {
  const localized = localizeDocumentMarkdown(source);
  return source.untranslated === undefined
    ? localized
    : `> ${source.untranslated.notice} <${source.untranslated.englishUrl}>\n\n${localized}`;
}

function localizeDocumentMarkdown({ body, pageLocale, relativePath, siteUrl, slug }: DocumentMarkdownSource): string {
  const sourceDirectory = posix.join("docs", posix.dirname(relativePath));
  const content = body.replace(LEADING_BLANK_LINES, "").replace(GENERATED_NOTICE, "");
  const published = publishLlmsText(rebaseMarkdownTargets(content, sourceDirectory), { siteUrl, slug });
  if (pageLocale === undefined) {
    return published;
  }
  const packageRoot = new URL(`/${slug}/`, siteUrl).href;
  const localizedPrefix = `/${pageLocale}/${slug}/`;
  const localizedRoot = new URL(localizedPrefix, siteUrl).href;
  return rewriteMarkdownTargets(published, (target) => {
    if (target.startsWith(localizedRoot)) {
      const url = new URL(target);
      // A published file such as an image has one English URL (`markdown-links.ts`).
      if (!url.pathname.endsWith("/")) {
        url.pathname = `/${slug}/${url.pathname.slice(localizedPrefix.length)}`;
      }
      return url.href;
    }
    if (!target.startsWith(packageRoot)) {
      return target;
    }
    const url = new URL(target);
    // A page route ends in a slash; a published file such as an image does not.
    if (url.pathname.endsWith("/")) {
      url.pathname = localizePath(pageLocale, url.pathname);
    }
    return url.href;
  });
}

/** Where a page's Markdown is published: `index.md` inside the page's own route. */
export function documentMarkdownRoute(route: string): string {
  return `${route}index.md`;
}
