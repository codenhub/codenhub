import { describe, expect, it } from "vitest";

import { renderReferencePage, symbolSlug } from "./reference-markdown.ts";
import type { ReferenceEntrypoint, ReferenceMember, ReferenceSymbol } from "./reference-model.ts";

function symbol(partial: Partial<ReferenceSymbol> & Pick<ReferenceSymbol, "name" | "kind">): ReferenceSymbol {
  return {
    typeParameters: [],
    parameters: [],
    throws: [],
    examples: [],
    see: [],
    members: [],
    namespaceMembers: [],
    overloads: [],
    ...partial,
  };
}

function member(partial: Partial<ReferenceMember> & Pick<ReferenceMember, "name" | "kind">): ReferenceMember {
  return {
    isOptional: false,
    isReadonly: false,
    isStatic: false,
    typeParameters: [],
    parameters: [],
    throws: [],
    examples: [],
    see: [],
    ...partial,
  };
}

const entrypoint: ReferenceEntrypoint = {
  subpath: ".",
  module: "index",
  internalTypes: [],
  symbols: [
    symbol({
      name: "createAppError",
      kind: "function",
      signature: "export declare function createAppError(error: unknown): AppError;",
      doc: "Normalizes an unknown value into an {@link AppError}.",
      deprecated: "Use createError instead.",
      parameters: [{ name: "error", doc: "The raw value." }],
      returns: "A frozen error.",
      throws: ["When options is not an object.", "When maxDepth is negative."],
      since: "1.2.0",
    }),
    symbol({
      name: "AppError",
      kind: "interface",
      signature: "export interface AppError extends Error",
      doc: "Normalized error shape.",
      members: [
        member({
          name: "messageKey",
          kind: "property",
          isOptional: true,
          isReadonly: true,
          doc: "Translation key.",
          signature: "readonly messageKey?: string;",
          defaultValue: '`"app.error"`',
        }),
        member({
          name: "origin",
          kind: "property",
          inheritedFrom: "ErrorFeedback",
        }),
        member({
          name: "toJSON",
          kind: "method",
          doc: "Serializes the error.",
          signature: "toJSON(space?: number): AppErrorJson;",
          parameters: [{ name: "space", doc: "Indentation passed through." }],
          returns: "A plain {@link AppError} snapshot.",
          throws: ["When the cause is circular."],
          deprecated: "Use serialize instead.",
        }),
      ],
    }),
    symbol({
      name: "ExternalThing",
      kind: "type-alias",
      signature: "export type ExternalThing = number;",
      doc: "See {@link https://mdn}.",
    }),
  ],
};

describe("renderReferencePage", () => {
  it.each(["true", "1", "'quoted'", "Name: thing # detail", 'a "quote" and \\ path'])(
    "preserves string frontmatter %s as quoted scalars",
    (value) => {
      const rendered = renderReferencePage(entrypoint, {
        title: value,
        description: value,
        since: value,
        group: value,
        heading: "Reference",
        sourceRoot: "src",
        prose: false,
      });
      for (const field of ["title", "description", "since", "group"]) {
        const scalar = rendered.match(new RegExp("^" + field + ": (.+)$", "m"))?.[1];
        expect(scalar).toBe(JSON.stringify(value));
        expect(JSON.parse(scalar ?? "null")).toBe(value);
      }
    },
  );

  const page = renderReferencePage(entrypoint, {
    title: "/",
    heading: "@codenhub/error",
    sourceRoot: "packages/error/src",
    group: "Reference",
    prose: true,
  });

  it("emits closed frontmatter, a generated notice, and a single H1", () => {
    expect(page.startsWith('---\ntitle: "/"\ngroup: "Reference"\n---\n')).toBe(true);
    expect(page).toContain("<!-- Generated by `pnpm generate` from packages/error/src. Do not edit. -->");
    expect(page.match(/^# /gm)).toHaveLength(1);
    expect(page).toContain("# @codenhub/error");
  });

  it("groups symbols under kind headings in spec order", () => {
    const headings = [...page.matchAll(/^## (.+)$/gm)].map((match) => match[1]);
    expect(headings).toEqual(["Functions", "Interfaces", "Type aliases"]);
  });

  it("allocates same-page links across the complete heading sequence", () => {
    const rendered = renderReferencePage(
      {
        ...entrypoint,
        symbols: [
          symbol({
            name: "Foo",
            kind: "function",
            doc: "# err\n\nSee {@link Foo}, {@link foo}, {@link Functions}, {@link Err}, {@link err}.",
          }),
          symbol({ name: "foo", kind: "function" }),
          symbol({ name: "Functions", kind: "function" }),
          symbol({ name: "Reader", kind: "interface", members: [member({ name: "err", kind: "property" })] }),
          symbol({ name: "Err", kind: "type-alias" }),
          symbol({ name: "err", kind: "variable" }),
        ],
      },
      { title: "Foo", heading: "Foo", sourceRoot: "src", prose: true },
    );
    expect(rendered).toContain("[Foo](#foo-1), [foo](#foo-2), [Functions](#functions-1), [Err](#err-2), [err](#err-3)");
  });

  it("nests prose headings below their symbol or member and caps them at H6", () => {
    const nested = renderReferencePage(
      {
        ...entrypoint,
        symbols: [
          symbol({
            name: "Reader",
            kind: "interface",
            doc: "# Summary\n\n## Remarks\n\nSetext\n======\n\n```md\n# Code\n```",
            returns: "Result.\n\n# Return details",
            members: [member({ name: "read", kind: "method", doc: "# Member\n\n###### Deep" })],
          }),
        ],
      },
      { title: "Reference", heading: "Reference", sourceRoot: "src", prose: true },
    );
    expect(nested).toContain("#### Summary\n\n##### Remarks\n\n#### Setext");
    expect(nested).toContain("#### Return details");
    expect(nested).toContain("##### Member\n\n###### Deep");
    expect(nested).toContain("```md\n# Code\n```");
  });

  it("preserves the complete text of multiline Setext headings in prose containers", () => {
    const rendered = renderReferencePage(
      {
        ...entrypoint,
        symbols: [
          symbol({
            name: "Reader",
            kind: "interface",
            doc: "First *line*\nsecond line\n===\n\n> Quoted first\n> second line\n> ---",
          }),
        ],
      },
      { title: "Reference", heading: "Reference", sourceRoot: "src", prose: true },
    );
    expect(rendered).toContain("#### First *line* second line");
    expect(rendered).toContain("> ##### Quoted first second line");
  });

  it("escapes HTML-looking prose while preserving code and Markdown links", () => {
    const rendered = renderReferencePage(
      {
        ...entrypoint,
        symbols: [
          symbol({
            name: "Reader",
            kind: "interface",
            doc: 'Returns a Map<K, V> or <T>, <br> and <span title="value">text</span>.\n\n<div>\n`<Inline>`\n\n```html\n<Fenced>\n```\n\n[Guide](https://example.com) and <https://example.com>. Already \\<Escaped\\>.',
            examples: ["Prose <Example> with `<Code>`."],
            parameters: [{ name: "value", doc: "A <Value>." }],
            returns: "A {@link <External>}.",
          }),
        ],
      },
      { title: "Reference", heading: "Reference", sourceRoot: "src", prose: true },
    );
    expect(rendered).toContain(
      'Returns a Map&lt;K, V&gt; or &lt;T&gt;, &lt;br&gt; and &lt;span title="value"&gt;text&lt;/span&gt;.',
    );
    expect(rendered).toContain("&lt;div&gt;\n`<Inline>`");
    expect(rendered).toContain("```html\n<Fenced>\n```");
    expect(rendered).toContain("[Guide](https://example.com) and <https://example.com>.");
    expect(rendered).toContain("Already \\<Escaped\\>.");
    expect(rendered).toContain("Prose &lt;Example&gt; with `<Code>`.");
    expect(rendered).toContain("A &lt;Value&gt;.");
    expect(rendered).toContain("A `<External>`.");
  });

  it("renders the signature, a deprecation blockquote, then prose and tag sections", () => {
    const section = page.slice(page.indexOf("### createAppError"), page.indexOf("### AppError"));
    expect(section).toContain("```ts\nexport declare function createAppError(error: unknown): AppError;\n```");
    expect(section).toContain("> **Deprecated.** Use createError instead.");
    expect(section).toContain("**Parameters**\n\n- `error` — The raw value.");
    expect(section).toContain("**Returns** — A frozen error.");
    expect(section).toContain("**Throws**\n\n- When options is not an object.\n- When maxDepth is negative.");
    expect(section).toContain("**Since** — 1.2.0");
    expect(section.indexOf("> **Deprecated.**")).toBeLessThan(section.indexOf("**Parameters**"));
  });

  it("emits description and since frontmatter when the entry module supplies them", () => {
    const enriched = renderReferencePage(entrypoint, {
      title: "/",
      heading: "@codenhub/error",
      sourceRoot: "packages/error/src",
      description: "Typed error normalization and result helpers.",
      since: "1.0.0",
      group: "Reference",
      prose: true,
    });
    expect(enriched).toContain(
      '---\ntitle: "/"\ndescription: "Typed error normalization and result helpers."\nsince: "1.0.0"\ngroup: "Reference"\n---\n',
    );
  });

  it("keeps the frontmatter version but drops the per-symbol Since line when prose is false", () => {
    const bare = renderReferencePage(entrypoint, {
      title: "/",
      heading: "@codenhub/error",
      sourceRoot: "packages/error/src",
      since: "1.0.0",
      order: 0,
      prose: false,
    });
    expect(bare).toContain('since: "1.0.0"');
    expect(bare).not.toContain("**Since**");
  });

  it("renders a single-entry Throws or See also section as one inline line", () => {
    const single = renderReferencePage(
      {
        subpath: ".",
        module: "index",
        internalTypes: [],
        symbols: [
          symbol({
            name: "unwrap",
            kind: "function",
            signature: "export declare function unwrap<T>(result: Result<T>): T;",
            doc: "Returns the value or throws.",
            throws: ["When the result is an Err."],
            see: ["unwrapOr"],
          }),
        ],
      },
      { title: "/", heading: "@codenhub/error", sourceRoot: "packages/error/src", prose: true },
    );
    expect(single).toContain("**Throws** — When the result is an Err.");
    expect(single).not.toContain("**Throws**\n\n-");
    expect(single).toContain("**See also** — unwrapOr");
  });

  it("keeps multiline tag bodies inside their list item or deprecation blockquote", () => {
    const body = "First paragraph.\n\n- alpha\n- beta\n\nSecond paragraph.";
    const rendered = renderReferencePage(
      {
        ...entrypoint,
        symbols: [
          symbol({
            name: "read",
            kind: "function",
            deprecated: body,
            parameters: [{ name: "input", doc: body }],
            typeParameters: [{ name: "T", doc: body }],
            throws: [body, "Other failure."],
            see: [body, "Other reference."],
          }),
        ],
      },
      { title: "Reference", heading: "Reference", sourceRoot: "src", prose: true },
    );
    const continuation = "First paragraph.\n\n  - alpha\n  - beta\n\n  Second paragraph.";
    expect(rendered).toContain("- `input` — " + continuation);
    expect(rendered).toContain("- `T` — " + continuation);
    expect(rendered).toContain("**Throws**\n\n- " + continuation + "\n- Other failure.");
    expect(rendered).toContain("**See also**\n\n- " + continuation + "\n- Other reference.");
    expect(rendered).toContain("> **Deprecated.** First paragraph.\n>\n> - alpha\n> - beta\n>\n> Second paragraph.");
  });

  it("resolves an in-page {@link} to a heading anchor and leaves unknown targets as code", () => {
    expect(page).toContain("Normalizes an unknown value into an [AppError](#apperror).");
    expect(page).toContain("See {@link https://mdn}.".replace("{@link https://mdn}", "`https://mdn`"));
  });

  it("resolves links in prose while preserving inline, fenced, and indented code", () => {
    const doc =
      'See {@link __DEV__}. Code: `{@link __DEV__}`.\n\n```ts\nconst doc = "{@link __DEV__}";\n```\n\n    {@link __DEV__}\n\nAfter {@link __DEV__ | __label__}.';
    const rendered = renderReferencePage(
      { ...entrypoint, symbols: [symbol({ name: "__DEV__", kind: "variable", doc })] },
      { title: "Reference", heading: "Reference", sourceRoot: "src", prose: true },
    );
    expect(rendered).toContain("See [\\_\\_DEV\\_\\_](#__dev__). Code: `{@link __DEV__}`.");
    expect(rendered).toContain('```ts\nconst doc = "{@link __DEV__}";\n```');
    expect(rendered).toContain("    {@link __DEV__}");
    expect(rendered).toContain("After [\\_\\_label\\_\\_](#__dev__).");
  });

  // A backtracking or rescanning pattern takes minutes on these inputs and exceeds the test timeout.
  it.each([
    ["one opening before long whitespace", `See {@link ${" ".repeat(50_000)}| ${" ".repeat(50_000)}.`],
    ["many openings", `See ${"{@link x ".repeat(20_000)}`],
  ])("scans unterminated links in linear time: %s", (_case, doc) => {
    const rendered = renderReferencePage(
      { ...entrypoint, symbols: [symbol({ name: "__DEV__", kind: "variable", doc })] },
      { title: "Reference", heading: "Reference", sourceRoot: "src", prose: true },
    );
    expect(rendered).toContain("See {@link ");
  });

  it("stops an unterminated link at the next opening so a later link still resolves", () => {
    const rendered = renderReferencePage(
      {
        ...entrypoint,
        symbols: [symbol({ name: "__DEV__", kind: "variable", doc: "See {@link broken, then {@link __DEV__}." })],
      },
      { title: "Reference", heading: "Reference", sourceRoot: "src", prose: true },
    );
    expect(rendered).toContain("See {@link broken, then [\\_\\_DEV\\_\\_](#__dev__).");
  });

  it("escapes generated identifiers and link labels so Markdown preserves their text", () => {
    const escaped = renderReferencePage(
      {
        ...entrypoint,
        symbols: [
          symbol({
            name: "__DEV__",
            kind: "variable",
            doc: "See {@link __DEV__ | __DEV__}. ",
            members: [member({ name: "*value*", kind: "property" })],
          }),
        ],
        internalTypes: [
          { name: "__Internal__", signature: "type __Internal__ = string;", declaredIn: ["src/index.ts"] },
        ],
      },
      { title: "Reference", heading: "[Reference] __API__", sourceRoot: "src", prose: true },
    );
    expect(escaped).toContain("# \\[Reference\\] \\_\\_API\\_\\_");
    expect(escaped).toContain("### \\_\\_DEV\\_\\_");
    expect(escaped).toContain("[\\_\\_DEV\\_\\_](#__dev__)");
    expect(escaped).toContain("#### \\*value\\*");
    expect(escaped).toContain("### \\_\\_Internal\\_\\_");
  });

  it("links an in-page {@link} to an internal type heading", () => {
    const rendered = renderReferencePage(
      {
        ...entrypoint,
        symbols: [symbol({ name: "parse", kind: "function", doc: "Returns {@link Options}." })],
        internalTypes: [{ name: "Options", signature: "type Options = {};", declaredIn: ["src/index.ts"] }],
      },
      { title: "Reference", heading: "Reference", sourceRoot: "src", prose: true },
    );
    expect(rendered).toContain("Returns [Options](#options).");
  });

  it("prefers a target documented on the current page over another page's copy", () => {
    const rendered = renderReferencePage(
      {
        ...entrypoint,
        symbols: [symbol({ name: "parse", kind: "function", doc: "Returns {@link Options}." })],
        internalTypes: [{ name: "Options", signature: "type Options = {};", declaredIn: ["src/index.ts"] }],
      },
      {
        title: "Reference",
        heading: "Reference",
        sourceRoot: "src",
        prose: true,
        resolveLink: () => "other.md#options",
      },
    );
    expect(rendered).toContain("Returns [Options](#options).");
  });

  it("renders interface members with their own heading and signature block", () => {
    expect(page).toContain("#### messageKey\n\n```ts\nreadonly messageKey?: string;\n```\n\nTranslation key.");
  });

  it("renders an inherited member as a link to its declaring type, with no signature block", () => {
    const section = page.slice(page.indexOf("#### origin"), page.indexOf("#### toJSON"));
    expect(section).toBe("#### origin\n\nInherited from `ErrorFeedback`.\n\n");

    const linked = renderReferencePage(entrypoint, {
      title: "/",
      heading: "@codenhub/error",
      sourceRoot: "packages/error/src",
      prose: true,
      resolveLink: (name) => (name === "ErrorFeedback" ? "feedback.md#errorfeedback" : undefined),
    });
    expect(linked).toContain("#### origin\n\nInherited from [ErrorFeedback](feedback.md#errorfeedback).");
  });

  it("omits an inherited member entirely when prose is false", () => {
    const bare = renderReferencePage(entrypoint, {
      title: "/",
      heading: "@codenhub/error",
      sourceRoot: "packages/error/src",
      order: 0,
      prose: false,
    });
    expect(bare).not.toContain("#### origin");
    expect(bare).not.toContain("Inherited from");
    // Own members are unaffected: they still get their heading and signature.
    expect(bare).toContain("#### messageKey\n\n```ts\nreadonly messageKey?: string;\n```");
  });

  it("renders a method member's documented parameters", () => {
    expect(page).toContain("#### toJSON");
    expect(page).toContain("Serializes the error.\n\n**Parameters**\n\n- `space` — Indentation passed through.");
  });

  it("renders a member's block tags through the same prose path as a symbol's", () => {
    expect(page).toContain(
      "#### messageKey\n\n```ts\nreadonly messageKey?: string;\n```\n\nTranslation key.\n\n" +
        '**Default** — `"app.error"`',
    );
    const section = page.slice(page.indexOf("#### toJSON"), page.indexOf("## Type aliases"));
    expect(section).toContain(
      "> **Deprecated.** Use serialize instead.\n\nSerializes the error.\n\n**Parameters**\n\n" +
        "- `space` — Indentation passed through.\n\n**Returns** — A plain [AppError](#apperror) snapshot.\n\n" +
        "**Throws** — When the cause is circular.",
    );
  });

  it("omits prose when prose is false", () => {
    const bare = renderReferencePage(entrypoint, {
      title: "/",
      heading: "@codenhub/error",
      sourceRoot: "packages/error/src",
      order: 0,
      prose: false,
    });
    expect(bare).toContain("### createAppError\n\n```ts");
    expect(bare).not.toContain("**Parameters**");
    expect(bare).not.toContain("> **Deprecated.**");
    expect(bare).not.toContain("**Returns**");
    expect(bare).not.toContain("**Default**");
    expect(bare).toContain("order: 0");
  });
});

describe("symbolSlug", () => {
  it("lower-cases a plain identifier and strips a leading sigil", () => {
    expect(symbolSlug("createAppError")).toBe("createapperror");
    expect(symbolSlug("$state")).toBe("state");
  });
});
