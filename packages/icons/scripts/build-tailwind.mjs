/**
 * Emits the published Tailwind plugin module.
 *
 * A Tailwind plugin handler has to be synchronous -- utilities registered after
 * an `await` are dropped -- so the families cannot be loaded on demand once the
 * plugin's options are known. They are imported statically instead, and this
 * module is generated because the family list is.
 */
import { mkdir, readdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageDirectory = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const dataDirectory = resolve(packageDirectory, "data");
const outputDirectory = resolve(packageDirectory, "dist", "tw");

const families = (
  await readdir(dataDirectory, { withFileTypes: true }).catch((error) => {
    if (error.code === "ENOENT") {
      return [];
    }
    throw error;
  })
)
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .toSorted((first, second) => first.localeCompare(second));

function identifier(prefix) {
  return prefix.replace(/-([a-z0-9])/g, (_, character) => character.toUpperCase());
}

const imports = families.map((prefix) => `import ${identifier(prefix)} from "../data/${prefix}.js";`).join("\n");
const list = families.map((prefix) => `  ${identifier(prefix)},`).join("\n");

const module = `// Generated by scripts/build-tailwind.mjs. Do not edit.
import { createIconsTailwindPlugin } from "../tailwind.js";
${imports}

export default createIconsTailwindPlugin([
${list}
]);
`;

const declaration = `declare const plugin: ReturnType<typeof import("../tailwind.js").createIconsTailwindPlugin>;
export default plugin;
`;

await mkdir(outputDirectory, { recursive: true });
await writeFile(resolve(outputDirectory, "plugin.js"), module, "utf8");
await writeFile(resolve(outputDirectory, "plugin.d.ts"), declaration, "utf8");

console.log(`Built dist/tw/plugin.js binding ${families.length} icon families.`);
